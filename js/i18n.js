/** Translate `key`, replacing `{name}` placeholders from `params`. */
export function t(key, params = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.pt[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : `{${k}}`));
}

export const LOCALES = { pt: 'pt-PT', en: 'en-GB' };

const fmtCache = new Map();
function fmt(opts, tz) {
  const key = `${lang}|${tz}|${JSON.stringify(opts)}`;
  if (!fmtCache.has(key)) fmtCache.set(key, new Intl.DateTimeFormat(LOCALES[lang], { timeZone: tz, ...opts }));
  return fmtCache.get(key);
}

/** "14/11/2026, 11:30" style date + time in zone `tz`. */
export const formatDateTime = (ms, tz) => fmt({ year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }, tz).format(ms);
export const formatTime = (ms, tz) => fmt({ hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }, tz).format(ms);
export const formatTimeSec = (ms, tz) => fmt({ hour: '2-digit', minute: '2-digit', second: '2-digit', hourCycle: 'h23' }, tz).format(ms);

/** UTC offset of `tz` at `ms`, as "+01:00". */
export function utcOffset(ms, tz) {
  const part = fmt({ timeZoneName: 'longOffset' }, tz).formatToParts(ms).find((p) => p.type === 'timeZoneName');
  const m = part?.value.match(/GMT([+-]\d{2}):?(\d{2})?/);
  return m ? `${m[1]}:${m[2] ?? '00'}` : '+00:00';
}

/** ISO-8601 local time with explicit offset, e.g. 2026-11-14T11:30:52+00:00. */
export function isoLocal(ms, tz) {
  const p = Object.fromEntries(new Intl.DateTimeFormat('en-CA', {
    timeZone: tz, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', second: '2-digit', hourCycle: 'h23',
  }).formatToParts(ms).map((x) => [x.type, x.value]));
  return `${p.year}-${p.month}-${p.day}T${p.hour}:${p.minute}:${p.second}${utcOffset(ms, tz)}`;
}

const MONTH_PT = ['jan', 'fev', 'mar', 'abr', 'mai', 'jun', 'jul', 'ago', 'set', 'out', 'nov', 'dez'];
const MONTH_PT_LONG = ['janeiro', 'fevereiro', 'março', 'abril', 'maio', 'junho', 'julho', 'agosto', 'setembro', 'outubro', 'novembro', 'dezembro'];
const WEEKDAY_PT = ['no domingo', 'na segunda', 'na terça', 'na quarta', 'na quinta', 'na sexta', 'no sábado'];
const WEEKDAY_PT_LONG = ['no domingo', 'na segunda-feira', 'na terça-feira', 'na quarta-feira', 'na quinta-feira', 'na sexta-feira', 'no sábado'];
const WEEKDAY_PT_SHORT = ['dom.', 'seg.', 'ter.', 'qua.', 'qui.', 'sex.', 'sáb.'];

function dayParts(ms, tz) {
  const parts = Object.fromEntries(new Intl.DateTimeFormat('en-GB', { timeZone: tz, weekday: 'short', day: 'numeric', month: 'numeric' })
    .formatToParts(ms).map((x) => [x.type, x.value]));
  return { wd: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'].indexOf(parts.weekday), day: parts.day, mon: Number(parts.month) - 1 };
}

/** Headline day: "na quinta-feira, 12 de novembro" / "on Thursday 12 November". */
export function formatDayLong(ms, tz) {
  const { wd, day, mon } = dayParts(ms, tz);
  if (lang === 'pt') return `${WEEKDAY_PT_LONG[wd]}, ${day} de ${MONTH_PT_LONG[mon]}`;
  return `on ${fmt({ weekday: 'long', day: 'numeric', month: 'long' }, tz).format(ms)}`;
}

/** Compact day for lists: "qui. 12 nov." / "Thu 12 Nov". */
export function formatDayShort(ms, tz) {
  const { wd, day, mon } = dayParts(ms, tz);
  if (lang === 'pt') return `${WEEKDAY_PT_SHORT[wd]} ${day} ${MONTH_PT[mon]}.`;
  return fmt({ weekday: 'short', day: 'numeric', month: 'short' }, tz).format(ms).replace(',', '');
}

// Readable names for the time zones of the main working areas; others fall
// back to the city part of the IANA name ("America/Sao_Paulo" -> "Sao Paulo").
const ZONE_NAMES = {
  'Europe/Lisbon': { pt: 'Lisboa', en: 'Lisbon' },
  'Atlantic/Madeira': { pt: 'Madeira', en: 'Madeira' },
  'Atlantic/Azores': { pt: 'Açores', en: 'the Azores' },
  'Africa/Maputo': { pt: 'Maputo', en: 'Maputo' },
  'Africa/Sao_Tome': { pt: 'São Tomé', en: 'São Tomé' },
  'Atlantic/Cape_Verde': { pt: 'Cabo Verde', en: 'Cape Verde' },
  'Africa/Bissau': { pt: 'Bissau', en: 'Bissau' },
  'Africa/Luanda': { pt: 'Luanda', en: 'Luanda' },
  'Europe/Madrid': { pt: 'Madrid', en: 'Madrid' },
  'Atlantic/Canary': { pt: 'Canárias', en: 'the Canaries' },
  'Europe/London': { pt: 'Londres', en: 'London' },
  'Europe/Paris': { pt: 'Paris', en: 'Paris' },
  'America/Sao_Paulo': { pt: 'São Paulo', en: 'São Paulo' },
  'Asia/Dili': { pt: 'Díli', en: 'Dili' },
  UTC: { pt: 'UTC', en: 'UTC' },
};

/** "Lisboa" / "Lisbon" for "Europe/Lisbon"; Etc/GMT zones are shown as UTC offsets. */
export function zoneName(tz) {
  if (ZONE_NAMES[tz]) return ZONE_NAMES[tz][lang] ?? ZONE_NAMES[tz].en;
  if (/^Etc\//.test(tz)) return lang === 'pt' ? 'fuso marítimo' : 'nautical zone';
  return tz.split('/').pop().replace(/_/g, ' ');
}

/** Duration in words: "3 dias e 21 h", "5 h 10 min", "40 min". */
export function formatDuration(msAbs) {
  const days = Math.floor(msAbs / 86400000);
  const hours = Math.floor((msAbs % 86400000) / 3600000);
  const mins = Math.round((msAbs % 3600000) / 60000);
  if (days) return t('dur_days_hours', { d: days, dl: t(days === 1 ? 'day_one' : 'day_other'), h: hours });
  if (hours) return t('dur_hours_mins', { h: hours, m: mins });
  return t('dur_mins', { m: mins });
}

/** Natural-language day: "na sexta, 14 nov" / "on Friday 14 Nov". */
export function formatDay(ms, tz) {
  const parts = Object.fromEntries(new Intl.DateTimeFormat('en-GB', { timeZone: tz, weekday: 'short', day: 'numeric', month: 'numeric' })
    .formatToParts(ms).map((x) => [x.type, x.value]));
  const wd = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'].indexOf(parts.weekday);
  if (lang === 'pt') {
    const mon = Number(parts.month) - 1;
    return `${WEEKDAY_PT[wd]}, ${parts.day} ${MONTH_PT[mon]}`;
  }
  return `on ${fmt({ weekday: 'long', day: 'numeric', month: 'short' }, tz).format(ms)}`;
}
