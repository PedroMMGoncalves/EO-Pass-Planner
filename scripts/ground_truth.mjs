// ground_truth.mjs: compare predicted pass times with real acquisition times.
//
// Inputs:  Earth Search STAC (sentinel-2-l2a, landsat-c2-l2) items over
//          mainland Portugal in the last N days (default 7); data/catalogue.json;
//          data/tles.json (current element sets, propagated backwards).
// Outputs: docs/validation.md (or --out PATH) with one row per scene and
//          summary statistics per platform; a JSON copy with --json PATH.
// Method:  for each scene, a point ROI at the centroid of its footprint; the
//          engine predicts the pass of the same satellite within ±30 min of
//          the STAC datetime; residual = predicted closest approach − STAC
//          datetime (Landsat: scene centre time; Sentinel-2 L2A: granule
//          sensing time).
// Limitations: element sets are propagated backwards by up to N days, so
//          residuals include TLE-age error; the STAC datetime conventions
//          differ slightly between missions; centroids of clipped tiles are
//          not exact scene centres.
// Usage:   node scripts/ground_truth.mjs [--days 7] [--out docs/validation.md] [--json path]

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { predictEntry } from '../js/engine.js';
import { prepareRoi } from '../js/geometry.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const DAYS = Number(opt('--days', 7));
const OUT = opt('--out', `${root}docs/validation.md`);
const JSON_OUT = opt('--json', null);

const catalogue = JSON.parse(readFileSync(`${root}data/catalogue.json`, 'utf8'));
const tles = JSON.parse(readFileSync(`${root}data/tles.json`, 'utf8'));
const ENTRY = {
  'sentinel-2a': 'S2A_MSI', 'sentinel-2b': 'S2B_MSI', 'sentinel-2c': 'S2C_MSI',
  'landsat-8': 'L8_OLI_TIRS', 'landsat-9': 'L9_OLI2_TIRS2',
};
const BBOX = '-9.6,36.9,-6.1,42.2';
const now = Date.now();
const from = new Date(now - DAYS * 86400000).toISOString();
const to = new Date(now).toISOString();

async function search(collection) {
  const out = [];
  let url = `https://earth-search.aws.element84.com/v1/search?collections=${collection}&bbox=${BBOX}&datetime=${from}/${to}&limit=100`;
  for (let page = 0; url && page < 5; page++) {
    const res = await fetch(url, { headers: { 'User-Agent': 'EO-Pass-Planner validation script' } });
    if (!res.ok) throw new Error(`${collection}: HTTP ${res.status}`);
    const fc = await res.json();
    out.push(...fc.features);
    url = (fc.links ?? []).find((l) => l.rel === 'next' && (!l.method || l.method === 'GET'))?.href;
  }
  return out;
}

function centroid(geom) {
  const ring = geom.type === 'Polygon' ? geom.coordinates[0] : geom.coordinates[0][0];
  const pts = ring.slice(0, -1);
  return [pts.reduce((s, p) => s + p[0], 0) / pts.length, pts.reduce((s, p) => s + p[1], 0) / pts.length];
}

const items = [...await search('sentinel-2-l2a'), ...await search('landsat-c2-l2')];
const rows = [];
const seen = new Set();
for (const it of items) {
  const plat = String(it.properties.platform).toLowerCase();
  const id = ENTRY[plat];
  if (!id) continue;
  const key = `${plat}|${it.properties['grid:code'] ?? it.properties['landsat:wrs_path'] + '/' + it.properties['landsat:wrs_row']}|${it.properties.datetime.slice(0, 16)}`;
  if (seen.has(key)) continue;
  seen.add(key);
  const entry = catalogue.entries.find((e) => e.id === id);
  const obs = Date.parse(it.properties.datetime);
  const [lon, lat] = centroid(it.geometry);
  const roi = prepareRoi({ type: 'Point', coordinates: [lon, lat] });
  const r = predictEntry({ ...entry, pass_filter: 'any' }, tles[String(entry.norad_id)], roi, obs - 1800000, obs + 1800000);
  const p = r.passes.sort((a, b) => Math.abs(a.closest_utc - obs) - Math.abs(b.closest_utc - obs))[0];
  rows.push({
    platform: entry.platform, item: it.id, observed: it.properties.datetime, lon, lat,
    residual_s: p ? (p.closest_utc - obs) / 1000 : null,
    edge_margin_km: p ? p.edge_margin_km : (r.reach_km - r.closest_km),
    tle_age_days: p ? p.tle_age_days : null,
  });
}
rows.sort((a, b) => a.observed.localeCompare(b.observed));

const stats = {};
for (const r of rows) {
  if (r.residual_s == null) continue;
  (stats[r.platform] ??= []).push(r.residual_s);
}
const fmt = (v, d = 2) => (v == null ? '–' : (v >= 0 ? '+' : '') + v.toFixed(d));
const lines = [
  '# Validation against real acquisitions',
  '',
  `Generated by \`node scripts/ground_truth.mjs --days ${DAYS}\` on ${new Date(now).toISOString().slice(0, 16)} UTC.`,
  '',
  `Scenes: Sentinel-2 L2A and Landsat Collection 2 Level-2 items from Earth Search STAC over mainland Portugal (bbox ${BBOX}), ${from.slice(0, 10)} to ${to.slice(0, 10)}.`,
  'For each scene, a point at the centroid of its footprint is used as ROI and the engine predicts the pass of the same satellite with the current element sets (propagated backwards).',
  'Residual = predicted closest approach − STAC datetime (Landsat: scene centre time; Sentinel-2 L2A: granule sensing time).',
  '',
  '## Summary',
  '',
  '| Platform | scenes | mean Δt (s) | s.d. (s) | max |Δt| (s) | missed |',
  '|---|---:|---:|---:|---:|---:|',
];
for (const plat of [...new Set(rows.map((r) => r.platform))].sort()) {
  const v = stats[plat] ?? [];
  const n = rows.filter((r) => r.platform === plat).length;
  const mean = v.reduce((s, x) => s + x, 0) / (v.length || 1);
  const sd = Math.sqrt(v.reduce((s, x) => s + (x - mean) ** 2, 0) / (v.length || 1));
  lines.push(`| ${plat} | ${n} | ${fmt(mean)} | ${sd.toFixed(2)} | ${v.length ? Math.max(...v.map(Math.abs)).toFixed(2) : '–'} | ${n - v.length} |`);
}
lines.push('', '## Residual against element-set age', '', 'Mean |Δt| (s) by the age of the element set at the pass (number of scenes in brackets).', '',
  '| Platform | 0–4 d | 4–8 d | 8–12 d | 12–16 d |', '|---|---:|---:|---:|---:|');
for (const plat of [...new Set(rows.map((r) => r.platform))].sort()) {
  const cells = [0, 4, 8, 12].map((lo) => {
    const v = rows.filter((r) => r.platform === plat && r.residual_s != null && r.tle_age_days >= lo && r.tle_age_days < lo + 4).map((r) => Math.abs(r.residual_s));
    return v.length ? `${(v.reduce((x, y) => x + y, 0) / v.length).toFixed(2)} (${v.length})` : '–';
  });
  lines.push(`| ${plat} | ${cells.join(' | ')} |`);
}
lines.push('', '"Missed" counts scenes whose footprint centroid lies outside the predicted nominal swath (no pass within ±30 min); their edge margin in the table is the negative distance to the swath edge. This happens for tiles only partly covered by the swath, whose centroid falls in the unimaged part.', '', '## Scenes', '',
  '| Platform | STAC item | observed (UTC) | Δt (s) | edge margin (km) | TLE age (d) |', '|---|---|---|---:|---:|---:|');
for (const r of rows) lines.push(`| ${r.platform} | ${r.item} | ${r.observed.slice(0, 19)} | ${fmt(r.residual_s)} | ${fmt(r.edge_margin_km, 1)} | ${r.tle_age_days == null ? '–' : r.tle_age_days.toFixed(1)} |`);
lines.push('', '## Interpretation', '',
  'The error grows with the age of the element set; an element set older than about a week, or one that spans an',
  'orbit-maintenance manoeuvre, can be off by several seconds. The data workflow refreshes element sets every 6 h.',
  'Timing residuals of a few seconds or less mean the predicted pass and the real acquisition coincide; the',
  'along-track ground speed is about 6.7–7 km/s, so 1 s corresponds to about 7 km along the track. A negative edge',
  'margin for a scene that was acquired shows that the nominal swath width or the tile footprint differs from the',
  'real swath edge by that amount.');
writeFileSync(OUT, lines.join('\n') + '\n');
if (JSON_OUT) writeFileSync(JSON_OUT, JSON.stringify(rows, null, 1));
console.log(`${rows.length} scenes; written ${OUT}`);
for (const [plat, v] of Object.entries(stats)) console.log(plat, v.length, 'max |dt|', Math.max(...v.map(Math.abs)).toFixed(2));
